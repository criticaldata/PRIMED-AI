"""E05: aggregate evaluation result JSONs into a unified file + paper-ready tables.

Collects the missing-modality (E01) and fairness (E03) result JSONs that exist under a
results directory and rebuilds a single ``results.json`` plus Markdown and LaTeX tables.
Designed to be re-runnable: one command regenerates every table from the raw JSONs.
"""
from __future__ import annotations

import json
from pathlib import Path

from primed_ai.probes.common import git_sha

CONDITION_LABELS = {
    "full": "Full (echo+ECG)",
    "echo_dropped": "Echo dropped (ECG-only)",
    "ecg_dropped": "ECG dropped (echo-only)",
}
ATTR_LABELS = {"sex": "Sex", "age_band": "Age band", "race": "Race"}


def _load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def _fmt(value: float | None, digits: int = 2) -> str:
    if value is None or (isinstance(value, float) and value != value):  # None or NaN
        return "--"
    return f"{value:.{digits}f}"


def aggregate_results(results_dir: str | Path = "results") -> dict:
    """Build the unified results payload from whatever result JSONs are present."""
    rd = Path(results_dir)
    mm = _load(rd / "missing_modality.json")
    fair = _load(rd / "fairness" / "fairness_metrics.json")

    agg: dict = {"task": "E05_results_aggregation", "git_sha": git_sha(), "sources": {}}

    if mm is not None:
        agg["sources"]["missing_modality"] = str(rd / "missing_modality.json")
        agg["missing_modality"] = {
            "n_test": mm.get("n", {}).get("test"),
            "conditions": mm.get("metrics_table", []),
        }
    if fair is not None:
        agg["sources"]["fairness"] = str(rd / "fairness" / "fairness_metrics.json")
        agg["fairness"] = {"overall": fair.get("overall"), "by": fair.get("by", {})}

    if not agg["sources"]:
        raise FileNotFoundError(f"No result JSONs found under {rd} (looked for missing_modality.json, fairness/)")
    return agg


def _mm_rows(agg: dict) -> list[dict]:
    return agg.get("missing_modality", {}).get("conditions", [])


def to_markdown(agg: dict) -> str:
    lines: list[str] = ["# Aggregated results", "", f"_git: `{agg['git_sha']}`_", ""]
    rows = _mm_rows(agg)
    if rows:
        n = agg["missing_modality"].get("n_test")
        lines += [f"## Missing-modality degradation (n={n})", "",
                  "| Condition | MAE | EF≤40% AUROC |", "|---|---:|---:|"]
        for r in rows:
            label = CONDITION_LABELS.get(r["condition"], r["condition"])
            lines.append(f"| {label} | {_fmt(r.get('mae'))} | {_fmt(r.get('ef40_auroc'), 3)} |")
        lines.append("")
    if "fairness" in agg:
        by = agg["fairness"].get("by", {})
        lines += ["## Fairness stratification", "",
                  "| Attribute | Group | n | MAE | EF≤40% AUROC |", "|---|---|---:|---:|---:|"]
        for attr, groups in by.items():
            for grp, m in groups.items():
                flag = " *" if m.get("small_n") else ""
                lines.append(
                    f"| {ATTR_LABELS.get(attr, attr)} | {grp}{flag} | {m.get('n')} "
                    f"| {_fmt(m.get('mae'))} | {_fmt(m.get('ef40_auroc'), 3)} |"
                )
        lines += ["", "_\\* small stratum (below minimum count)._"]
    return "\n".join(lines) + "\n"


def to_latex(agg: dict) -> str:
    out: list[str] = []
    rows = _mm_rows(agg)
    if rows:
        n = agg["missing_modality"].get("n_test")
        out += [
            "% Missing-modality degradation (auto-generated by aggregate_results)",
            "\\begin{table}[t]\\centering",
            f"\\caption{{Missing-modality degradation on the held-out test set (n={n}).}}",
            "\\label{tab:degradation-agg}\\small",
            "\\begin{tabular}{@{}lcc@{}}\\toprule",
            "\\textbf{Condition} & \\textbf{MAE}\\,$\\downarrow$ & \\textbf{EF\\,$\\leq$\\,40\\% AUROC}\\,$\\uparrow$ \\\\ \\midrule",
        ]
        for r in rows:
            label = CONDITION_LABELS.get(r["condition"], r["condition"]).replace("+", "$+$")
            out.append(f"{label} & {_fmt(r.get('mae'))} & {_fmt(r.get('ef40_auroc'), 3)} \\\\")
        out += ["\\bottomrule\\end{tabular}\\end{table}", ""]
    if "fairness" in agg:
        out += [
            "% Fairness stratification (auto-generated by aggregate_results)",
            "\\begin{table}[t]\\centering",
            "\\caption{Per-stratum LVEF error and HFrEF-gate discrimination. $^{*}$ small stratum.}",
            "\\label{tab:fairness-agg}\\small",
            "\\begin{tabular}{@{}llccc@{}}\\toprule",
            "\\textbf{Attribute} & \\textbf{Group} & \\textbf{n} & \\textbf{MAE} & \\textbf{EF\\,$\\leq$\\,40\\% AUROC} \\\\ \\midrule",
        ]
        for attr, groups in agg["fairness"].get("by", {}).items():
            for grp, m in groups.items():
                star = "$^{*}$" if m.get("small_n") else ""
                out.append(
                    f"{ATTR_LABELS.get(attr, attr)} & {grp}{star} & {m.get('n')} "
                    f"& {_fmt(m.get('mae'))} & {_fmt(m.get('ef40_auroc'), 3)} \\\\"
                )
        out += ["\\bottomrule\\end{tabular}\\end{table}", ""]
    return "\n".join(out)


def write_all(agg: dict, out_dir: str | Path = "results") -> dict[str, str]:
    out = Path(out_dir)
    tables = out / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    paths = {
        "json": out / "results.json",
        "markdown": tables / "results.md",
        "latex": tables / "results.tex",
    }
    paths["json"].write_text(json.dumps(agg, indent=2))
    paths["markdown"].write_text(to_markdown(agg))
    paths["latex"].write_text(to_latex(agg))
    return {k: str(v) for k, v in paths.items()}
